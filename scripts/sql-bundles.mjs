import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Ranges are release metadata; SQL bodies exist only in migrations/.
export const bundles = {
  'StudyHub_update_v0.16.sql': [11, 13],
  'StudyHub_update_v0.20.sql': [14, 14],
  'StudyHub_update_v0.23.sql': [15, 15],
  'StudyHub_update_v0.26.sql': [16, 16],
  'StudyHub_update_v0.27.sql': [16, 17],
  'StudyHub_update_v0.28.sql': [16, 18],
  'StudyHub_update_v0.30.sql': [16, 19],
  'StudyHub_update_v0.31.sql': [16, 20],
  'StudyHub_update_v0.35.sql': [21, 21],
  'StudyHub_update_v0.42.sql': [22, 22],
  'StudyHub_update_v0.43.sql': [22, 23],
  'StudyHub_update_v0.45.sql': [22, 24],
  'StudyHub_update_v0.47.sql': [25, 25],
  'StudyHub_upgrade_to_v0.35.sql': [11, 21],
};
export async function renderBundles() {
  const names = (await readdir('supabase/migrations')).filter((n) => n.endsWith('.sql')).sort();
  const sources = await Promise.all(
    names.map(async (name) => ({
      name,
      number: Number(name.match(/(\d{3})_[^/]+\.sql$/)[1]),
      sql: await readFile('supabase/migrations/' + name, 'utf8'),
    })),
  );
  return new Map(
    Object.entries({
      ...bundles,
      'StudyHub_upgrade_latest.sql': [11, Math.max(...sources.map((s) => s.number))],
    }).map(([name, [from, to]]) => {
      const selected = sources.filter((s) => s.number >= from && s.number <= to);
      if (selected.length !== to - from + 1) throw Error('Missing migration in ' + name);
      const header =
        '-- GENERATED by npm run sql:generate. DO NOT EDIT.\n-- Canonical SQL: supabase/migrations/. Existing database required.\n';
      const body = selected
        .map(
          ({ name, sql }) =>
            `-- ${name}; sha256=${createHash('sha256').update(sql).digest('hex')}\n` +
            sql.replace(/^\s*(begin|commit);\s*$/gim, '').trim(),
        )
        .join('\n\n');
      // All post-foundation migrations are repeatable. One transaction protects data on failure.
      const guard =
        from === 11
          ? `do $$begin
 if to_regclass('public.profiles') is null or to_regclass('public.private_notes') is null or to_regclass('public.course_reader_states') is null then
  raise exception 'This is not the existing StudyHub database (base migrations 001-010 required). Check the selected Supabase project; no changes were applied.';
 end if;
end $$;\n`
          : '';
      return [name, header + 'begin;\n' + guard + '\n' + body + '\ncommit;\n'];
    }),
  );
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let failed = false;
  for (const [name, sql] of await renderBundles()) {
    const path = 'supabase/' + name;
    if (check) {
      if ((await readFile(path, 'utf8').catch(() => null)) !== sql) {
        console.error('STALE generated SQL:', path);
        failed = true;
      }
    } else await writeFile(path, sql);
  }
  if (failed) process.exitCode = 1;
  else
    console.log(
      check
        ? 'SQL bundles match canonical migrations.'
        : 'SQL bundles generated from canonical migrations.',
    );
}
